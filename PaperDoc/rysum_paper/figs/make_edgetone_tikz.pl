#!/usr/bin/perl
# Writes edgetone.tex: the mouth tone of the unstable wind model (WindChaos.h, since 14 Nov 2026)
# as the stop wind falls - the same control law as fig_edgetone() in make_figs.py, with
# f_top = 4 f0 (the middle of the pipe's range 2.3 .. 6 x f0 at middle c), drawn in TikZ.
#   perl make_edgetone_tikz.pl > edgetone.tex
use strict; use warnings; use POSIX qw(floor);

my $f0 = 262.0;
sub res { my $k = shift; return $f0 * $k * (1 + 0.0025 * ($k - 1)); }
sub rnd { my $x = shift; return floor($x + 0.5); }

sub run {
    my ($lock, $stopped, $fTop, $wOn) = @_;
    $fTop //= 4.0 * $f0; $wOn //= 0.45;
    my $n = 900; my @ws; push @ws, $wOn + ($_ / ($n - 1)) * (0.03 - $wOn) for 0 .. $n - 1;
    my $nearest = sub {
        my $hz = shift; my $k = rnd($hz / $f0); $k = 1 if $k < 1;
        if ($stopped && $k % 2 == 0) { $k += $hz > res($k) ? 1 : -1; }
        return $k < 1 ? 1 : $k;
    };
    my ($k, $f) = (-1, 0); my (@out, @amp);
    for my $w (@ws) {
        my $ff = $fTop * sqrt(($w > 0.005 ? $w : 0.005) / $wOn);
        if ($k < 1) { $k = $nearest->($ff); }
        else {
            my $sp = $stopped ? 2.0 : 1.0;
            $k = $nearest->($ff) if abs($ff - res($k)) / ($f0 * $sp) > 0.5 + 0.3 * $lock;
        }
        my $fT = exp(log($ff) + $lock * (log(res($k)) - log($ff)));
        $f = $f == 0 ? $fT : $f + 0.35 * ($fT - $f);
        push @out, $f;
        my $x = $w / $wOn; my $on = (1 - $x) / 0.12; $on = 1 if $on > 1;
        push @amp, $on * $x ** 1.3;
    }
    return (\@ws, \@out, \@amp);
}

# axes: left panel x = wind 45 % (left) .. 3 % (right), y = 0 .. 1200 Hz; right panel y = -40 .. 2 dB
my ($W1, $W2, $H, $gap) = (8.2, 4.6, 3.4, 2.5);
my ($wHi, $wLo) = (46, 2);
sub X { my ($w, $W) = @_; return sprintf "%.3f", ($wHi - $w * 100) / ($wHi - $wLo) * $W; }
sub path {
    my ($ws, $ys, $W, $ymap, $step) = @_; my @p;
    for (my $i = 0; $i < @$ws; $i += $step) { push @p, "(" . X($ws->[$i], $W) . "," . sprintf("%.3f", $ymap->($ys->[$i])) . ")"; }
    return join(" -- ", @p);
}
my $yF = sub { my $hz = shift; return $hz / 1200 * $H; };
my $yL = sub { my $a = shift; my $db = 20 * log($a > 1e-4 ? $a : 1e-4) / log(10); $db = -40 if $db < -40; return ($db + 40) / 42 * $H; };

print "% generated by make_edgetone_tikz.pl - do not edit\n";
print "\\begin{tikzpicture}[font=\\footnotesize, x=1cm, y=1cm]\n";
# left frame, harmonics, ticks
print "\\draw[muted, line width=0.4pt] (0,0) rectangle ($W1,$H);\n";
for my $k (1 .. 4) { my $y = $yF->(res($k)); printf "\\draw[muted!60, dotted, line width=0.4pt] (0,%.3f) -- ($W1,%.3f) node[right, text=muted, font=\\scriptsize] {%d\$f_0\$};\n", $y, $y, $k; }
for my $hz (0, 300, 600, 900, 1200) { my $y = $yF->($hz); printf "\\draw[muted] (0,%.3f) -- (-0.08,%.3f) node[left, text=ink2] {%d};\n", $y, $y, $hz; }
for my $w (40, 30, 20, 10) { my $x = X($w / 100, $W1); print "\\draw[muted] ($x,0) -- ($x,-0.08) node[below, text=ink2] {$w};\n"; }
printf "\\node[text=ink2, rotate=90] at (-1.0,%.2f) {mouth-tone frequency [Hz]};\n", $H / 2;
printf "\\node[text=ink2] at (%.2f,-0.75) {stop wind [\\%%]  (falling \\(\\rightarrow\\))};\n", $W1 / 2;
my @curves = ([0.05, 0, 'muted', 'free (lock 0.05)'], [0.85, 0, 's1', 'open pipe, lock 0.85'], [0.85, 1, 'rysred', 'stopped pipe, lock 0.85']);
my $ly = $H - 0.25;
for my $c (@curves) {
    my ($ws, $f) = run($c->[0], $c->[1]);
    print "\\draw[$c->[2], line width=1.0pt, line join=round] ", path($ws, $f, $W1, $yF, 6), ";\n";
    printf "\\draw[$c->[2], line width=1.0pt] (%.2f,%.2f) -- (%.2f,%.2f) node[right, text=ink2, font=\\scriptsize] {$c->[3]};\n", $W1 - 3.3, $ly, $W1 - 2.9, $ly;
    $ly -= 0.32;
}
# right panel: level
my $o = $W1 + $gap;
print "\\begin{scope}[xshift=${o}cm]\n";
print "\\draw[muted, line width=0.4pt] (0,0) rectangle ($W2,$H);\n";
for my $db (0, -10, -20, -30, -40) { my $y = ($db + 40) / 42 * $H; printf "\\draw[muted] (0,%.3f) -- (-0.08,%.3f) node[left, text=ink2] {%d};\n", $y, $y, $db; }
for my $w (40, 30, 20, 10) { my $x = X($w / 100, $W2); print "\\draw[muted] ($x,0) -- ($x,-0.08) node[below, text=ink2] {$w};\n"; }
printf "\\node[text=ink2, rotate=90] at (-0.85,%.2f) {mouth-tone level [dB]};\n", $H / 2;
printf "\\node[text=ink2] at (%.2f,-0.75) {stop wind [\\%%]};\n", $W2 / 2;
{ my ($ws, undef, $a) = run(0.5, 0); print "\\draw[s1, line width=1.0pt, line join=round] ", path($ws, $a, $W2, $yL, 6), ";\n"; }
print "\\end{scope}\n";
print "\\end{tikzpicture}\n";
